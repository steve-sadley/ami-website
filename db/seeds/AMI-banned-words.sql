-- somebody being unpleasant in polite language, which is what most forum trouble
-- actually looks like, and that is what the report route and a moderator hiding a
-- post are for. And it will not stop somebody determined, who will spell around
-- it. It is here to catch the angry post written at four in the afternoon, and it
