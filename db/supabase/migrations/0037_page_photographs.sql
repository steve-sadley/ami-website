-- =============================================================================
-- 0037  The page photographs become content
--
-- Thirteen photographs on ten public pages: eight banners, the photograph band
-- on the home page, and the picture beside four "split" panels. Until now each
-- was a file in the bundle named in the markup, and changing one needed a
-- deployment. They waited on 0036, because the upload stored whatever it was
-- given; it now converts every picture before it leaves the browser.
--
-- WHAT A PHOTOGRAPH BLOCK HOLDS. One address in `body`, of one of two shapes:
--
--   /assets/photo-team.webp           a photograph the bundle already carries
--   pages/2026/agm-hall-k3x9qa.webp   a converted upload in public-media
--
-- Seeded with the first shape, so each starts as exactly the picture the page
-- shows today, and the Pages screen opens on the real photograph rather than
-- an empty box.
--
-- WHY THE ADDRESS IS CHECKED HERE AS WELL AS IN THE BROWSER. The site writes
-- it into a CSS url('...'). A quote or a bracket in it would end the url and
-- start CSS of somebody's choosing. site.js refuses anything off the pattern;
-- the database refuses it first, so a value that could do that is never
-- stored however it was written.
--
-- The hero on the home page is NOT here. Its four photographs rotate in step
-- with the hero statements, which are their own table, and the pairing rule in
-- page-index.js would need rethinking. A separate job.
--
-- Safe to run twice.
-- =============================================================================

alter table public.page_blocks drop constraint if exists page_blocks_photo_address;
alter table public.page_blocks add  constraint page_blocks_photo_address check (
  block_key not like '%\_photo'
  or (items is null
      and body is not null
      and body ~ '^(/assets/[a-z0-9-]+\.webp|[a-z0-9][a-z0-9/_-]*\.(webp|jpg))$')
);
-- `body is not null` is said out loud because a CHECK passes on null. Without
-- it, a regular expression against a missing address answers null rather than
-- false and the row goes in. Test 18 found that on its first run.

comment on constraint page_blocks_photo_address on public.page_blocks is
  'A block whose key ends _photo holds one picture address: /assets/<name>.webp '
  'from the bundle, or a public-media path ending .webp or .jpg. Nothing that '
  'could close the CSS url() the site writes it into.';

